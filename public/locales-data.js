/** Deduplicate by value, keep first occurrence after sort by label */
function dedupeByValue(items) {
  const seen = new Set();
  const out = [];
  for (const item of items) {
    if (seen.has(item.value)) continue;
    seen.add(item.value);
    out.push(item);
  }
  return out;
}

const sorted = [...LOCALES_UNSORTED].sort((a, b) => a.label.localeCompare(b.label, "en"));

export const LOCALES = dedupeByValue(sorted);
